"""Build the WorkflowHub upload zip for the AI Document Formatter.

    python deploy/workflowhub/build_zip.py

Writes dist-workflowhub/ai-document-formatter.zip with, at the zip root:
    node.yaml, docker-compose.yml, .env   (from this folder)
    backend/, frontend/                  (the tracked source, minus tests and build output)

The .env holds the database password. It is generated once into deploy/workflowhub/.env
(git-ignored) and reused on later builds, so a re-upload keeps the same password.
"""
from __future__ import annotations

import secrets
import subprocess
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "dist-workflowhub" / "ai-document-formatter.zip"
ENV_FILE = HERE / ".env"

INCLUDE_DIRS = ("backend/", "frontend/")
EXCLUDE_PARTS = ("/tests/", "/node_modules/", "/dist/", "/.venv/", "/__pycache__/")
EXCLUDE_FILES = {"backend/requirements-dev.txt", "backend/.env.example"}

ENV_TEMPLATE = """\
# WorkflowHub runtime settings for the AI Document Formatter (read by the api and db services).
# Generated by build_zip.py. Do not commit: it holds the database password.

POSTGRES_USER=docformatter
POSTGRES_PASSWORD={password}
POSTGRES_DB=docformatter
DATABASE_URL=postgresql+asyncpg://docformatter:{password}@db:5432/docformatter

# LLM server (must be reachable from the machine that runs WorkflowHub)
OLLAMA_URL=http://192.168.0.84:11434
OLLAMA_MODEL=gpt-oss:20b

MAX_CONCURRENT_JOBS=1
MAX_QUEUED_JOBS=20
MAX_UPLOAD_MB=20
LOG_LEVEL=INFO
"""


def ensure_env() -> None:
    if not ENV_FILE.exists():
        ENV_FILE.write_text(ENV_TEMPLATE.format(password=secrets.token_urlsafe(24)), encoding="utf-8")
        print(f"Generated {ENV_FILE.relative_to(ROOT)} (new database password)")


def source_files() -> list[str]:
    """Tracked + untracked-but-not-ignored files under backend/ and frontend/."""
    out = subprocess.run(
        ["git", "ls-files", "--cached", "--others", "--exclude-standard", *INCLUDE_DIRS],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout.splitlines()
    files = []
    for rel in sorted(set(out)):
        if rel in EXCLUDE_FILES or any(p in f"/{rel}" for p in EXCLUDE_PARTS):
            continue
        if (ROOT / rel).is_file():
            files.append(rel)
    return files


def main() -> int:
    ensure_env()
    OUT.parent.mkdir(exist_ok=True)
    files = source_files()
    # zipfile always writes forward-slash paths (PowerShell 5's Compress-Archive does not,
    # which breaks unzipping on Linux).
    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.write(HERE / "node.yaml", "node.yaml")
        zf.write(HERE / "docker-compose.yml", "docker-compose.yml")
        zf.write(ENV_FILE, ".env")
        for rel in files:
            info = zipfile.ZipInfo.from_file(ROOT / rel, rel)
            if rel.endswith(".sh"):
                info.external_attr = (0o100755 << 16)  # keep the entrypoint executable
            info.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(info, (ROOT / rel).read_bytes())
    size_kb = OUT.stat().st_size / 1024
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(files) + 3} files, {size_kb:.0f} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
